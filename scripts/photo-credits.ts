// Regenerates PHOTOS.md from the photo source map and activity data. Run: npx tsx scripts/photo-credits.ts
import { writeFileSync } from 'node:fs'
import { activities } from '../src/data/activities'
import { photoSourceUrl, photoSources } from '../src/data/photos'

const rows = Object.keys(photoSources)
  .sort()
  .map((name) => {
    const used = activities.filter((a) => a.image.name === name)
    const where = used.map((a) => `[${a.title}](/guide/${a.id})`).join(', ') || '—'
    const alt = used[0]?.image.alt ?? ''
    return `| \`${name}\` | ${alt} | ${where} | ${photoSourceUrl(name)} |`
  })

const md = `# Photo sources

All photographs are from [Unsplash](https://unsplash.com) and are used under the [Unsplash Licence](https://unsplash.com/license),
which allows free use without permission or attribution. We credit Unsplash in the site footer and link each guide's photograph to its source.

Each image was downloaded once from Unsplash's image CDN, resized to 900px and 1800px wide, recompressed, and bundled in \`public/images\`
as \`<name>-sm.jpg\` and \`<name>-lg.jpg\`. The site makes no requests to Unsplash at runtime. Unsplash photographer names were not
available to this build and are not listed; the source URLs below identify each photograph.

If an image fails to load, the site shows a neutral panel with the image description instead (see \`Photo\` in \`src/components/ui.tsx\`).

| File | Description (alt text) | Used by | Source |
| --- | --- | --- | --- |
${rows.join('\n')}

_Generated by \`scripts/photo-credits.ts\` from \`src/data/photos.ts\`._
`

writeFileSync('PHOTOS.md', md)
console.log(`Wrote PHOTOS.md (${rows.length} photographs)`)
